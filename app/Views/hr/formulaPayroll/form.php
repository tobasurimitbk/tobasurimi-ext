                        <div class="form-floating mb-3" style="height: 50px;">
                            <input type="text" class="form-control nama_formula" id="nama_formula" name="nama_formula" placeholder="Nama Formula">
                            <label for="floatingInput">Nama Formula</label>
                        </div>
                    </div>

                    <div class="col-md-6">
                        <div class="form-floating mb-3" style="height: 50px;">
